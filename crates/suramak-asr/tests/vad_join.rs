// ---------------------------------------------------------------------------
// Text alignment: dropped / duplicated phrases and WER from one alignment
// ---------------------------------------------------------------------------

/// One edit operation of a word-level alignment.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Op {
    /// Reference word `i` is hypothesis word `j`.
    Match,
    /// Reference word `i` was decoded as a different hypothesis word `j`.
    Sub,
    /// Reference word `i` is missing from the hypothesis.
    Del,
    /// Hypothesis word `j` has no reference counterpart.
    Ins,
}

/// Levenshtein alignment of two word sequences, with a backtrace.
///
/// Unit costs; ties prefer match, then substitution, then deletion. Sequences
/// are word vectors already normalized by [`normalize`].
fn align(reference: &[String], hypothesis: &[String]) -> Vec<Op> {
    let n = reference.len();
    let m = hypothesis.len();
    let width = m + 1;
    let mut cost = vec![0u32; (n + 1) * width];
    for (i, row) in cost.chunks_mut(width).enumerate() {
        row[0] = i as u32;
    }
    for (j, cell) in cost[..=m].iter_mut().enumerate() {
        *cell = j as u32;
    }
    for i in 1..=n {
        for j in 1..=m {
            let substitution =
                cost[(i - 1) * width + (j - 1)] + u32::from(reference[i - 1] != hypothesis[j - 1]);
            let deletion = cost[(i - 1) * width + j] + 1;
            let insertion = cost[i * width + (j - 1)] + 1;
            cost[i * width + j] = substitution.min(deletion).min(insertion);
        }
    }

    let mut ops = Vec::with_capacity(n.max(m));
    let (mut i, mut j) = (n, m);
    while i > 0 || j > 0 {
        let here = cost[i * width + j];
        if i > 0
            && j > 0
            && reference[i - 1] == hypothesis[j - 1]
            && here == cost[(i - 1) * width + (j - 1)]
        {
            ops.push(Op::Match);
            i -= 1;
            j -= 1;
        } else if i > 0 && j > 0 && here == cost[(i - 1) * width + (j - 1)] + 1 {
            ops.push(Op::Sub);
            i -= 1;
            j -= 1;
        } else if i > 0 && here == cost[(i - 1) * width + j] + 1 {
            ops.push(Op::Del);
            i -= 1;
        } else {
            ops.push(Op::Ins);
            j -= 1;
        }
    }
    ops.reverse();
    ops
}

/// Lowercase word tokens; everything that is not alphanumeric, `'` or `-`
/// separates words. Punctuation and casing never count as an edit.
fn normalize(text: &str) -> Vec<String> {
    text.split(|c: char| !(c.is_alphanumeric() || c == '\'' || c == '-'))
        .filter(|word| !word.is_empty())
        .map(|word| word.to_lowercase())
        .collect()
}

fn words_of(segments: &[Segment]) -> Vec<String> {
    normalize(
        &segments
            .iter()
            .map(|segment| segment.text.as_str())
            .collect::<Vec<_>>()
            .join(" "),
    )
}

/// Word error rate in percent (`(S + D + I) / N * 100`).
fn wer(reference: &[String], hypothesis: &[String]) -> f64 {
    if reference.is_empty() {
        return if hypothesis.is_empty() { 0.0 } else { 100.0 };
    }
    let errors = align(reference, hypothesis)
        .iter()
        .filter(|op| !matches!(op, Op::Match))
        .count();
    errors as f64 * 100.0 / reference.len() as f64
}

/// The phrase-level verdict of one comparison.
#[derive(Debug, Default, Clone)]
struct PhraseDiff {
    /// Maximal runs of ≥ 2 reference words that the hypothesis lacks.
    dropped: Vec<String>,
    /// Reference words that are missing (single-word runs included).
    dropped_words: usize,
    /// Inserted runs of ≥ 2 words that also occur in the reference: a
    /// duplication at the join.
    duplicated: Vec<String>,
    /// Inserted words that occur nowhere in the reference: hallucination, not
    /// duplication (reported, and counted by WER).
    extra: Vec<String>,
}

/// Splits the alignment into dropped/duplicated phrase runs.
///
/// A dropped phrase is a maximal `Del` run; a duplicated phrase is a maximal
/// `Ins` run whose word sequence also appears in the reference (a re-decode of
/// already-covered audio). Short intrusions (`".", "thank you"`) are reported
/// but only phrases of ≥ 2 words gate, because a single extra token is a
/// decoder artefact rather than a lost or repeated phrase.
fn phrase_diff(reference: &[String], hypothesis: &[String]) -> PhraseDiff {
    let ops = align(reference, hypothesis);
    let mut diff = PhraseDiff::default();
    let (mut i, mut j) = (0usize, 0usize);
    let mut index = 0usize;
    while index < ops.len() {
        match ops[index] {
            Op::Match | Op::Sub => {
                i += 1;
                j += 1;
                index += 1;
            }
            Op::Del => {
                let start = i;
                while index < ops.len() && ops[index] == Op::Del {
                    i += 1;
                    index += 1;
                }
                let run = &reference[start..i];
                diff.dropped_words += run.len();
                if run.len() >= 2 {
                    diff.dropped.push(run.join(" "));
                }
            }
            Op::Ins => {
                let start = j;
                while index < ops.len() && ops[index] == Op::Ins {
                    j += 1;
                    index += 1;
                }
                let run = &hypothesis[start..j];
                if run.len() >= 2 && contains_run(reference, run) {
                    diff.duplicated.push(run.join(" "));
                } else {
                    diff.extra.push(run.join(" "));
                }
            }
        }
    }
    diff
}

/// Whether `needle` occurs as a contiguous run inside `haystack`.
fn contains_run(haystack: &[String], needle: &[String]) -> bool {
    if needle.is_empty() || needle.len() > haystack.len() {
        return false;
    }
    haystack
        .windows(needle.len())
        .any(|window| window == needle)
}

