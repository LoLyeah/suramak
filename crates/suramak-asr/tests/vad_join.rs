/// One audio fixture under test.
struct Fixture {
    label: &'static str,
    path: PathBuf,
    lang: LangMode,
    /// Reviewed text; when absent the full pass is the reference.
    reference: Option<String>,
    /// Whether this row counts toward the gate verdict (controls do not).
    gated: bool,
}

/// The model directory the fixtures' manifest and WAVs live in.
fn repo_fixture(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../fixtures/audio")
        .join(name)
}

fn m16df_dir() -> PathBuf {
    std::env::var_os("SURAMAK_VAD_FIXTURES")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("/tmp/m16df"))
}

fn require_vad() -> bool {
    std::env::var("SURAMAK_REQUIRE_VAD").as_deref() == Ok("1")
}

fn skip_or_fail(message: &str) {
    if require_vad() {
        panic!("SURAMAK_REQUIRE_VAD=1 but {message}");
    }
    eprintln!("skipping: {message}");
}

/// The pinned Silero model, via `SURAMAK_VAD_MODEL_PATH` (never committed).
fn vad_model() -> Option<PathBuf> {
    match std::env::var_os("SURAMAK_VAD_MODEL_PATH") {
        Some(path) => {
            let path = PathBuf::from(path);
            if path.is_file() {
                Some(path)
            } else {
                skip_or_fail(&format!(
                    "SURAMAK_VAD_MODEL_PATH points at {} which is not a file",
                    path.display()
                ));
                None
            }
        }
        None => {
            skip_or_fail("SURAMAK_VAD_MODEL_PATH is not set (the Silero model is not committed)");
            None
        }
    }
}

/// whisper models: `tiny` from the standard data dir, `base` from the M16DF
/// cache when present. `SURAMAK_VAD_MODELS=id=path,id=path` overrides both.
fn whisper_models() -> Vec<(String, PathBuf)> {
    if let Ok(list) = std::env::var("SURAMAK_VAD_MODELS") {
        let models: Vec<(String, PathBuf)> = list
            .split(',')
            .filter_map(|entry| entry.split_once('='))
            .map(|(id, path)| (id.to_string(), PathBuf::from(path)))
            .filter(|(_, path)| path.is_file())
            .collect();
        if !models.is_empty() {
            return models;
        }
        skip_or_fail("SURAMAK_VAD_MODELS named no existing model file");
        return Vec::new();
    }
    let mut models = Vec::new();
    if let Ok(dir) = suramak_core::paths::models_dir() {
        let tiny = dir.join("ggml-tiny.bin");
        if tiny.is_file() {
            models.push(("tiny".to_string(), tiny));
        }
    }
    if let Some(home) = std::env::var_os("HOME") {
        let base = PathBuf::from(home).join(".cache/m16df-models/ggml-base.bin");
        if base.is_file() {
            models.push(("base".to_string(), base));
        }
    }
    if models.is_empty() {
        skip_or_fail("no whisper model found (tiny in the data dir or base in the M16DF cache)");
    }
    models
}

/// Reads a fixture through the product's decode path (16 kHz mono in → the
/// same samples, no resampling).
fn read_pcm(path: &Path) -> Vec<f32> {
    let buffer = suramak_core::decode::decode_file(path).expect("decode fixture");
    assert_eq!(buffer.channels, 1, "{} is not mono", path.display());
    assert_eq!(buffer.rate, 16_000, "{} is not 16 kHz", path.display());
    suramak_core::resample::to_16khz_mono(&buffer).expect("resample")
}

fn manifest_text(name: &str) -> Option<String> {
    let manifest = repo_fixture("manifest.tsv");
    let text = std::fs::read_to_string(manifest).ok()?;
    text.lines()
        .filter_map(|line| line.split_once('\t'))
        .find(|(id, _)| *id == name)
        .map(|(_, text)| text.to_string())
}

/// The gate's fixture table. Missing files are skipped individually.
fn fixtures() -> Vec<Fixture> {
    let dir = m16df_dir();
    let mut out = Vec::new();
    let mut add = |label: &'static str,
                   path: PathBuf,
                   lang: LangMode,
                   reference: Option<String>,
                   gated: bool,
                   optional: bool| {
        if path.is_file() {
            out.push(Fixture {
                label,
                path,
                lang,
                reference,
                gated,
            });
        } else if !optional {
            skip_or_fail(&format!("fixture {label} is missing at {}", path.display()));
        }
    };
    add(
        "en",
        repo_fixture("en.wav"),
        LangMode::Fixed("en".into()),
        manifest_text("en"),
        true,
        false,
    );
    add(
        "en-room",
        dir.join("en-room.wav"),
        LangMode::Fixed("en".into()),
        manifest_text("en"),
        true,
        false,
    );
    add(
        "id",
        repo_fixture("id.wav"),
        LangMode::Fixed("id".into()),
        manifest_text("id"),
        true,
        false,
    );
    add(
        "id-room",
        dir.join("id-room.wav"),
        LangMode::Fixed("id".into()),
        manifest_text("id"),
        true,
        false,
    );
    // The mixed fixture: one language has to be pinned per session (whisper's
    // per-chunk auto detection flaps between EN and ID and would make the
    // comparison a language test, not a join test). `en` is the first and
    // longest cue; the `auto` row below measures the flapping separately.
    add(
        "60s-clean",
        dir.join("m16df-60s-clean.wav"),
        LangMode::Fixed("en".into()),
        None,
        true,
        false,
    );
    add(
        "60s-room",
        dir.join("m16df-60s-room.wav"),
        LangMode::Fixed("en".into()),
        None,
        true,
        false,
    );
    // Control, not part of the gate: the same 60 s timeline with the Indonesian
    // cues muted — is join quality clean when the audio is monolingual?
    add(
        "60s-enonly",
        dir.join("m16df-60s-enonly.wav"),
        LangMode::Fixed("en".into()),
        None,
        false,
        true,
    );
    out
}

