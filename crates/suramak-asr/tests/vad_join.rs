//! M16.4-S1 — the VAD join-quality gate.
//!
//! Answers the one question that decides whether chunk-only capture may be
//! built: **does VAD-driven chunking lose or duplicate words at the cut,
//! versus the full-pass transcript?**
//!
//! Per fixture and per whisper model: (a) a full pass over the whole file is
//! the authority; (b) the file is chunked by [`suramak_asr::vad`], each chunk is
//! transcribed with the same parameters, and the chunk decodes are joined with
//! M7's rule; (c) the two texts are aligned word-for-word.
//!
//! ## The gate (per row)
//!
//! * **zero dropped phrases** — no maximal run of ≥ 2 reference words missing
//!   from the joined text;
//! * **≤ 1 duplicated phrase** — an inserted run of ≥ 2 words that also occurs
//!   in the reference (a re-decode that the 50 ms tolerance failed to drop);
//! * **WER delta ≤ 1.0 pt** — against the reviewed text where one exists
//!   (`fixtures/audio/manifest.tsv` for EN/ID), else against the full pass.
//!
//! Rows marked `diagnostic` (language `auto` flapping, forced 4 s chunks) are
//! printed and measured but never gate: they exist to separate join damage
//! from a configuration change the production design owns (session language
//! pinning, chunk floor).
//!
//! ## Running it
//!
//! ```text
//! SURAMAK_VAD_MODEL_PATH=/tmp/silero_vad_v5.1.2.onnx \
//! SURAMAK_VAD_FIXTURES=/tmp/m16df \
//! LD_LIBRARY_PATH=target/debug \
//! cargo test -p suramak-asr --release --features vad-chunking \
//!   --test vad_join -- --ignored --nocapture
//! ```
//!
//! Fixtures: `fixtures/audio/{en,id}.wav` (committed), `$DIR/m16df-60s-clean.wav`
//! and `$DIR/m16df-60s-room.wav` (regenerated by the M16DF command), and the
//! room-tone variants `$DIR/{en,id}-room.wav` (the same pink-noise mix at
//! −55 dBFS, seed 20261110). A missing fixture is skipped with a message;
//! `SURAMAK_REQUIRE_VAD=1` turns any skip (model or fixture) into a failure.

#![cfg(feature = "vad-chunking")]

