#[test]
fn identical_text_has_no_dropped_or_duplicated_phrases() {
    let reference = normalize("The quick brown fox jumps over the lazy dog.");
    let diff = phrase_diff(&reference, &reference);
    assert!(diff.dropped.is_empty());
    assert!(diff.duplicated.is_empty());
    assert_eq!(diff.dropped_words, 0);
    assert_eq!(wer(&reference, &reference), 0.0);
}

#[test]
fn punctuation_and_case_do_not_count_as_edits() {
    let reference = normalize("Selamat pagi! Nama saya Suramak.");
    let hypothesis = normalize("selamat pagi nama saya suramak");
    assert_eq!(wer(&reference, &hypothesis), 0.0);
    assert!(phrase_diff(&reference, &hypothesis).dropped.is_empty());
}

#[test]
fn a_missing_sentence_is_one_dropped_phrase() {
    let reference = normalize("one two three four. five six seven eight.");
    let hypothesis = normalize("one two three four.");
    let diff = phrase_diff(&reference, &hypothesis);
    assert_eq!(diff.dropped, vec!["five six seven eight".to_string()]);
    assert_eq!(diff.dropped_words, 4);
    assert!((wer(&reference, &hypothesis) - 50.0).abs() < 1e-9);
}

