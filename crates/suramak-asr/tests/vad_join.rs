/// The 512 invariant and the boundary margins on the 60 s fixture, with no
/// whisper model involved.
#[test]
#[ignore = "needs the Silero model and the M16DF fixtures"]
fn chunk_boundaries_hold_on_the_sixty_second_fixture() {
    let Some(vad_model) = vad_model() else { return };
    let dir = m16df_dir();
    let clean = dir.join("m16df-60s-clean.wav");
    if !clean.is_file() {
        skip_or_fail(&format!("fixture is missing at {}", clean.display()));
        return;
    }
    let samples = read_pcm(&clean);
    let config = VadConfig::default();

    // Determinism: three fresh VAD runs over the same PCM.
    let runs: Vec<Vec<VadChunk>> = (0..3)
        .map(|_| vad::chunk_pcm(&vad_model, &samples, &config).expect("vad"))
        .collect();
    assert_eq!(runs[0], runs[1], "run 2 differs from run 1");
    assert_eq!(runs[0], runs[2], "run 3 differs from run 1");
    let chunks = &runs[0];
    let segments = vad::segments_with_model(&vad_model, &samples, &config).expect("vad");
    eprintln!(
        "determinism: 3/3 identical, {} chunks, {} VAD segments, feed 512 samples ({:.1}% audio decoded)",
        chunks.len(),
        segments.len(),
        100.0 * vad::chunk_audio_ms(chunks) as f64
            / (samples.len() as f64 / 16.0)
    );
    for (index, segment) in segments.iter().enumerate() {
        eprintln!(
            "  segment {index:>2}: {:>7.3}..{:>7.3} s ({:.3} s)",
            segment.start as f64 / 16_000.0,
            segment.end as f64 / 16_000.0,
            segment.len() as f64 / 16_000.0
        );
    }
    for (index, chunk) in chunks.iter().enumerate() {
        eprintln!(
            "  chunk {index}: {:>7.3}..{:>7.3} s (core {:>7.3}, {:.3} s)",
            chunk.start_ms() as f64 / 1000.0,
            chunk.end_ms() as f64 / 1000.0,
            chunk.core_start_ms() as f64 / 1000.0,
            chunk.len() as f64 / 16_000.0
        );
    }

    // Boundary margins against an independent −42 dBFS energy gate (M16DF's
    // reference measurement): the cut must sit after the last voiced frame and
    // ≥ 90 ms before the next one.
    let runs = energy_runs(&samples, -42.0, 100);
    assert!(runs.len() > 3, "the energy gate found no speech");
    let mut after: Vec<i64> = Vec::new();
    let mut before: Vec<i64> = Vec::new();
    for chunk in chunks.iter().take(chunks.len().saturating_sub(1)) {
        let cut = chunk.end;
        let last_voiced_end = runs
            .iter()
            .take_while(|(start, _)| (start + 1) * 512 <= cut)
            .last()
            .map(|(_, end)| (end + 1) * 512);
        let next_voiced_start = runs
            .iter()
            .find(|(start, _)| *start * 512 >= cut)
            .map(|(start, _)| start * 512);
        if let Some(last) = last_voiced_end {
            let margin = (cut as i64 - last as i64) / 16;
            assert!(margin >= 0, "cut at {cut} is inside voiced audio");
            after.push(margin);
        }
        if let Some(next) = next_voiced_start {
            let margin = (next as i64 - cut as i64) / 16;
            assert!(
                margin >= 90,
                "cut at {cut} is only {margin} ms before the next voiced frame"
            );
            before.push(margin);
        }
    }
    eprintln!(
        "boundary margins: {} cuts, cut after last voiced frame {:?} ms, cut before next voiced frame {:?} ms",
        after.len(),
        after,
        before
    );
    assert!(
        chunks.len() >= 3,
        "a 60 s fixture must produce several chunks, got {}",
        chunks.len()
    );
}

/// The gate itself: full pass vs chunked join, per fixture and model.
#[test]
#[ignore = "needs the Silero model, whisper models and the M16DF fixtures"]
fn vad_join_gate_across_fixtures() {
    let Some(vad_model) = vad_model() else { return };
    let models = whisper_models();
    if models.is_empty() {
        return;
    }
    let fixtures = fixtures();
    if fixtures.is_empty() {
        return;
    }
    // Iteration knob: `SURAMAK_VAD_ONLY=60s-clean,id` narrows the gate run.
    let only: Option<Vec<String>> = std::env::var("SURAMAK_VAD_ONLY").ok().map(|list| {
        list.split(',')
            .map(|item| item.trim().to_string())
            .collect()
    });
    let fixtures: Vec<Fixture> = match &only {
        Some(only) => fixtures
            .into_iter()
            .filter(|fixture| {
                only.iter()
                    .any(|name| fixture.label.starts_with(name.as_str()))
            })
            .collect(),
        None => fixtures,
    };
    let mut config = VadConfig::default();
    // Harness knob for the pre-roll comparison in the M16D1 report.
    if let Ok(ms) = std::env::var("SURAMAK_VAD_PRE_ROLL_MS") {
        config.pre_roll_ms = ms.parse().expect("SURAMAK_VAD_PRE_ROLL_MS is not a number");
    }
    let mut rows: Vec<Row> = Vec::new();

    for (model_id, model) in &models {
        let mut cache = ContextCache::new();
        eprintln!("== model {model_id} ({}) ==", model.display());
        for fixture in &fixtures {
            rows.push(measure(
                &mut cache,
                model_id,
                model,
                fixture,
                &config,
                &vad_model,
                fixture.gated,
            ));
        }

        // Diagnostic 0a: fixed 30 s cuts, no VAD — separates "these cuts" from
        // "per-chunk decoding" as the cause of a delta.
        if let Some(fixture) = fixtures.iter().find(|f| f.label == "60s-clean") {
            let samples = read_pcm(&fixture.path);
            let chunks = fixed_chunks(samples.len(), 30_000, 500);
            let mut row = measure_chunks(
                &mut cache, model_id, model, fixture, &samples, &chunks, false,
            );
            row.fixture = "60s-clean+fixed30s".to_string();
            rows.push(row);
        }

        // Diagnostic 1: a shorter chunk floor on the short fixtures, so the EN
        // and ID rows exercise a real join instead of a single whole-file chunk.
        let short = VadConfig {
            min_chunk_ms: 4_000,
            pause_ms: 500,
            ..config.clone()
        };
        for fixture in fixtures
            .iter()
            .filter(|f| f.label.starts_with("en") || f.label.starts_with("id"))
        {
            let mut row = measure(
                &mut cache, model_id, model, fixture, &short, &vad_model, false,
            );
            row.fixture = format!("{}+min4s", fixture.label);
            rows.push(row);
        }

        // Diagnostic 2: whisper's per-chunk language auto-detection on the
        // mixed fixture — measured, never gated (a session pin is slice 2's job).
        if let Some(fixture) = fixtures.iter().find(|f| f.label == "60s-clean") {
            let auto = Fixture {
                label: "60s-clean+auto",
                path: fixture.path.clone(),
                lang: LangMode::Auto,
                reference: None,
                gated: false,
            };
            rows.push(measure(
                &mut cache, model_id, model, &auto, &config, &vad_model, false,
            ));
        }
    }

    eprintln!("\n== gate table ==");
    for row in &rows {
        print_row(row);
    }

    let gated: Vec<&Row> = rows.iter().filter(|row| row.gated).collect();
    let failed: Vec<&&Row> = gated.iter().filter(|row| !row.gate_ok()).collect();
    eprintln!(
        "\ngated rows: {}, passed: {}, failed: {}",
        gated.len(),
        gated.len() - failed.len(),
        failed.len()
    );

    // Machine-readable copy for the report.
    let out = std::env::var_os("SURAMAK_VAD_JOIN_OUT")
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../target/vad-join-gate.json")
        });
    let json = serde_json::json!({
        "vad_config": {
            "threshold": config.threshold,
            "min_silence_s": config.min_silence_duration,
            "min_speech_s": config.min_speech_duration,
            "max_speech_s": config.max_speech_duration,
            "min_chunk_ms": config.min_chunk_ms,
            "max_chunk_ms": config.max_chunk_ms,
            "pause_ms": config.pause_ms,
            "pre_roll_ms": config.pre_roll_ms,
        },
        "rows": rows.iter().map(|row| serde_json::json!({
            "model": row.model,
            "fixture": row.fixture,
            "lang": row.lang,
            "gated": row.gated,
            "verdict": row.verdict(),
            "chunks": row.chunks,
            "chunk_audio_s": (row.chunk_audio_s * 1000.0).round() / 1000.0,
            "full_words": row.full_words,
            "chunk_words": row.chunk_words,
            "dropped_phrases": row.dropped,
            "dropped_words": row.dropped_words,
            "duplicated_phrases": row.duplicated,
            "extra_phrases": row.extra,
            "wer_full_vs_reference": row.wer_full_ref,
            "wer_chunk_vs_reference": row.wer_chunk_ref,
            "wer_delta_pt": (row.wer_delta * 100.0).round() / 100.0,
            "wer_chunk_vs_full": (row.wer_chunk_vs_full * 100.0).round() / 100.0,
        })).collect::<Vec<_>>(),
    });
    if let Ok(text) = serde_json::to_string_pretty(&json) {
        if let Some(parent) = out.parent() {
            let _ = std::fs::create_dir_all(parent);
        }
        std::fs::write(&out, text).expect("write the gate JSON");
        eprintln!("wrote {}", out.display());
    }

    assert!(
        failed.is_empty(),
        "the join gate failed on {} row(s): {:?}",
        failed.len(),
        failed
            .iter()
            .map(|row| format!(
                "{} / {}: dropped {:?}, duplicated {:?}, werΔ {:+.2}",
                row.model, row.fixture, row.dropped, row.duplicated, row.wer_delta
            ))
            .collect::<Vec<_>>()
    );
}
