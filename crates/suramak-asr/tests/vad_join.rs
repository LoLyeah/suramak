/// One measured row of the gate table.
#[derive(Debug, Clone)]
struct Row {
    model: String,
    fixture: String,
    lang: String,
    gated: bool,
    chunks: usize,
    chunk_audio_s: f64,
    full_words: usize,
    chunk_words: usize,
    dropped: Vec<String>,
    dropped_words: usize,
    duplicated: Vec<String>,
    extra: Vec<String>,
    wer_full_ref: Option<f64>,
    wer_chunk_ref: Option<f64>,
    wer_delta: f64,
    wer_chunk_vs_full: f64,
}

impl Row {
    fn gate_ok(&self) -> bool {
        self.dropped.is_empty() && self.duplicated.len() <= 1 && self.wer_delta <= 1.0
    }

    fn verdict(&self) -> &'static str {
        if !self.gated {
            if self.gate_ok() {
                "info-ok"
            } else {
                "info"
            }
        } else if self.gate_ok() {
            "PASS"
        } else {
            "FAIL"
        }
    }
}

/// Transcribes one buffer with the product's whisper parameters.
fn transcribe(
    cache: &mut ContextCache,
    model: &Path,
    samples: &[f32],
    lang: &LangMode,
) -> Vec<Segment> {
    let plan = EngineDecision {
        engine: EngineId::Cpu,
        warning: None,
    };
    let cancel = CancelToken::new();
    let ctx = cache.get_or_load(model, false).expect("load model");
    whisper::transcribe(
        ctx,
        model,
        samples,
        lang,
        None,
        whisper::default_threads(),
        &plan,
        &cancel,
        0,
        0,
        |_| {},
        &mut |_| {},
    )
    .expect("transcribe")
    .segments
}

/// Runs one (model, fixture) pair: full pass, VAD chunked pass, join, metrics.
fn measure(
    cache: &mut ContextCache,
    model_id: &str,
    model: &Path,
    fixture: &Fixture,
    config: &VadConfig,
    vad_model: &Path,
    gated: bool,
) -> Row {
    let samples = read_pcm(&fixture.path);
    let chunks = vad::chunk_pcm(vad_model, &samples, config).expect("vad");
    measure_chunks(cache, model_id, model, fixture, &samples, &chunks, gated)
}

/// Fixed-span chunks at `span_ms` (a control: no VAD involvement at all).
fn fixed_chunks(total: usize, span_ms: u32, pre_roll_ms: u32) -> Vec<VadChunk> {
    let span = span_ms as usize * 16;
    let pre_roll = pre_roll_ms as usize * 16;
    let mut chunks = Vec::new();
    let mut core = 0;
    loop {
        let end = (core + span).min(total);
        let start = if chunks.is_empty() {
            0
        } else {
            core - pre_roll
        };
        chunks.push(VadChunk {
            start,
            core_start: core,
            end,
        });
        if end >= total {
            break;
        }
        core = end;
    }
    chunks
}

/// The measurement itself over an explicit chunk list.
fn measure_chunks(
    cache: &mut ContextCache,
    model_id: &str,
    model: &Path,
    fixture: &Fixture,
    samples: &[f32],
    chunks: &[VadChunk],
    gated: bool,
) -> Row {
    let started = Instant::now();

    // (a) The authority: one pass over the whole file.
    let full = transcribe(cache, model, samples, &fixture.lang);

    // (b) Decode each chunk, join with M7's rule.
    let decoded: Vec<vad::ChunkDecode> = chunks
        .iter()
        .map(|chunk| vad::ChunkDecode {
            chunk: *chunk,
            segments: transcribe(cache, model, chunk.slice(samples), &fixture.lang),
        })
        .collect();
    let joined = vad::join_decoded(&decoded);

    // (c) Compare.
    let full_words = words_of(&full);
    let chunk_words = words_of(&joined);
    if std::env::var("SURAMAK_VAD_DUMP").as_deref() == Ok("1") {
        eprintln!(
            "--- {} / {} (lang {}) full pass:\n{}",
            model_id,
            fixture.label,
            lang_label(&fixture.lang),
            full.iter()
                .map(|segment| segment.text.as_str())
                .collect::<Vec<_>>()
                .join(" ")
        );
        for (index, decode) in decoded.iter().enumerate() {
            eprintln!(
                "--- chunk {index} [{}..{} s] core {} s:\n{}",
                decode.chunk.start_ms() as f64 / 1000.0,
                decode.chunk.end_ms() as f64 / 1000.0,
                decode.chunk.core_start_ms() as f64 / 1000.0,
                decode
                    .segments
                    .iter()
                    .map(|segment| segment.text.as_str())
                    .collect::<Vec<_>>()
                    .join(" ")
            );
        }
        eprintln!(
            "--- {} / {} joined:\n{}",
            model_id,
            fixture.label,
            joined
                .iter()
                .map(|segment| segment.text.as_str())
                .collect::<Vec<_>>()
                .join(" ")
        );
    }
    let diff = phrase_diff(&full_words, &chunk_words);
    let (wer_full_ref, wer_chunk_ref, wer_delta) = match &fixture.reference {
        Some(reference) => {
            let reference = normalize(reference);
            let full_wer = wer(&reference, &full_words);
            let chunk_wer = wer(&reference, &chunk_words);
            (Some(full_wer), Some(chunk_wer), chunk_wer - full_wer)
        }
        // No reviewed text: the full pass is the authority, so its own WER is
        // zero and the delta is the chunked run's distance from it.
        None => (None, None, wer(&full_words, &chunk_words)),
    };
    let audio_ms: i64 = chunks.iter().map(|c| c.end_ms() - c.start_ms()).sum();

    eprintln!(
        "  {} / {} (lang {}) → {} chunks, {:.1} s audio, {:.1} s wall",
        model_id,
        fixture.label,
        lang_label(&fixture.lang),
        chunks.len(),
        audio_ms as f64 / 1000.0,
        started.elapsed().as_secs_f64()
    );

    Row {
        model: model_id.to_string(),
        fixture: fixture.label.to_string(),
        lang: lang_label(&fixture.lang).to_string(),
        gated,
        chunks: chunks.len(),
        chunk_audio_s: audio_ms as f64 / 1000.0,
        full_words: full_words.len(),
        chunk_words: chunk_words.len(),
        dropped: diff.dropped,
        dropped_words: diff.dropped_words,
        duplicated: diff.duplicated,
        extra: diff.extra,
        wer_full_ref,
        wer_chunk_ref,
        wer_delta,
        wer_chunk_vs_full: wer(&full_words, &chunk_words),
    }
}

fn lang_label(lang: &LangMode) -> &str {
    match lang {
        LangMode::Auto => "auto",
        LangMode::Fixed(code) => code,
    }
}

fn print_row(row: &Row) {
    eprintln!(
        "{:<5} {:<6} {:<10} {:<4} chunks={:<2} audio={:>5.1}s words {}/{} dropped={} ({}w) dup={} extra={} werΔ={:+.2}pt wer_vs_full={:.2}%",
        row.verdict(),
        row.model,
        row.fixture,
        row.lang,
        row.chunks,
        row.chunk_audio_s,
        row.full_words,
        row.chunk_words,
        row.dropped.len(),
        row.dropped_words,
        row.duplicated.len(),
        row.extra.len(),
        row.wer_delta,
        row.wer_chunk_vs_full
    );
    for phrase in &row.dropped {
        eprintln!("        DROPPED: {phrase:?}");
    }
    for phrase in &row.duplicated {
        eprintln!("        DUPLICATED: {phrase:?}");
    }
    for phrase in &row.extra {
        if !phrase.trim().is_empty() {
            eprintln!("        extra: {phrase:?}");
        }
    }
}

// ---------------------------------------------------------------------------
// Energy gate: boundary margins on the 60 s fixture
// ---------------------------------------------------------------------------

/// Runs of 512-sample frames above `threshold_dbfs`, gaps ≤ `hangover_ms`
/// filled. The independent reference M16DF used for its margin table.
fn energy_runs(pcm: &[f32], threshold_dbfs: f32, hangover_ms: u32) -> Vec<(usize, usize)> {
    let threshold = 10f32.powf(threshold_dbfs / 20.0);
    let levels: Vec<f32> = pcm
        .chunks(512)
        .map(|frame| {
            let mean = frame.iter().map(|s| s * s).sum::<f32>() / frame.len() as f32;
            mean.sqrt()
        })
        .collect();
    let hangover = (hangover_ms / 32).max(1) as usize;
    let voiced: Vec<usize> = levels
        .iter()
        .enumerate()
        .filter(|(_, level)| **level > threshold)
        .map(|(index, _)| index)
        .collect();
    let mut runs: Vec<(usize, usize)> = Vec::new();
    for index in voiced {
        match runs.last_mut() {
            Some(last) if index - last.1 <= hangover => last.1 = index,
            _ => runs.push((index, index)),
        }
    }
    runs
}

